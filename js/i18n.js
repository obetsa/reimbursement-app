// ── Active language ──
let currentLang = localStorage.getItem('lang') || 'uk';

// ── Translate function ──
function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
    || (TRANSLATIONS['uk'] && TRANSLATIONS['uk'][key])
    || key;
}

// ── Apply translations to DOM ──
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if(el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
}

// ── Set language ──
function setLang(lang, el) {
  currentLang = lang;
  localStorage.setItem('lang', lang);

  document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
  if(el) el.classList.add('active');

  applyTranslations();
  showToast(t('toast.lang_changed') + ': ' + {uk:'Українська', de:'Deutsch', en:'English'}[lang], 'success');
}

// ── Load saved language ──
function loadSavedLang() {
  const saved = localStorage.getItem('lang') || 'uk';
  currentLang = saved;
  // Update active button
  const btn = document.querySelector(`.lang-btn[onclick*="'${saved}'"]`);
  if(btn) {
    document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
  }
  applyTranslations();
}
